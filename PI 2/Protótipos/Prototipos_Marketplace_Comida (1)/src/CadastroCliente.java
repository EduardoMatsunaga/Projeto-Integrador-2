    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        Cliente c = new Cliente();
        c.Cliente();
        GenericDao dao = new GenericDao();

        // variáveis
        c.cpf = txtCPF.getText();
        c.nome = txtNome.getText();
        c.telefone = txtTel.getText();
        c.email = txtEmail.getText();
        c.senha = txtSenha.getText();
        c.cep = txtCep.getText();
        c.logradouro = txtLogradouro.getText();
        c.numero = Integer.parseInt(txtNumero.getText());
        c.complemento = txtComplemento.getText();
        
        try {
            c.insertCliente(c);
        } catch (ClassNotFoundException ex) {
            System.getLogger(CadastroCliente.class.getName()).log(System.Logger.Level.ERROR, (String) null, ex);
        } catch (SQLException ex) {
            System.getLogger(CadastroCliente.class.getName()).log(System.Logger.Level.ERROR, (String) null, ex);
        }
        
        txtCPF.setText("");
        txtNome.setText("");
        txtTel.setText("");
        txtEmail.setText("");
        txtSenha.setText("");
        txtCep.setText("");
        txtLogradouro.setText("");
        txtNumero.setText("");
        txtComplemento.setText("");
        
        JOptionPane.showMessageDialog(null, "Usuário cadastrado com Sucesso");
    }//GEN-LAST:event_jButton1ActionPerformed

