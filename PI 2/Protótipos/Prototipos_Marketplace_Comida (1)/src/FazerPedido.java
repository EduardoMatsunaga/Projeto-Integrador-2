    private void carregarProdutos() {

    String sql = "SELECT nome FROM produto ORDER BY nome";

    carregandoProdutos = true;

    try (Connection conn = new GenericDao().getConnection();
         PreparedStatement ps = conn.prepareStatement(sql);
         ResultSet rs = ps.executeQuery()) {

        cmbProduto.removeAllItems();

        while (rs.next()) {

            cmbProduto.addItem(rs.getString("nome"));

        }

    } catch (Exception e) {

        JOptionPane.showMessageDialog(
            this,
            "Erro ao carregar produtos: " + e.getMessage()
        );

    } finally {

        carregandoProdutos = false;

    }
}
    
    private void atualizarProduto() {

    String nome = (String) cmbProduto.getSelectedItem();

    produtoId = 0;

    btnCompra.setEnabled(false);

    if (nome == null) {
        return;
    }

    String sql = "SELECT id, nome, descricao, valor, quantidade, nutricao "
               + "FROM produto WHERE nome = ?";

    try (Connection conn = new GenericDao().getConnection();
         PreparedStatement ps = conn.prepareStatement(sql)) {

        ps.setString(1, nome);

        try (ResultSet rs = ps.executeQuery()) {

            if (rs.next()) {

                produtoId = rs.getInt("id");

                precoUnitario = rs.getBigDecimal("valor");

                estoqueDisponivel = rs.getInt("quantidade");

                lblNome.setText(rs.getString("nome"));

                lblDesc.setText(rs.getString("descricao"));

                NumberFormat moeda =
                    NumberFormat.getCurrencyInstance(
                        new Locale("pt", "BR")
                    );

                lblValor.setText(
                    moeda.format(precoUnitario)
                );

                lblAlergicos.setText(
                    "Nutrição: " + rs.getString("nutricao")
                );

                if (estoqueDisponivel <= 0) {

                    spnQuantidade.setEnabled(false);

                    btnCompra.setEnabled(false);

                    JOptionPane.showMessageDialog(
                        this,
                        "Produto sem estoque disponível."
                    );

                } else {

                    spnQuantidade.setEnabled(true);

                    btnCompra.setEnabled(true);

                    spnQuantidade.setModel(
                        new SpinnerNumberModel(
                            1,
                            1,
                            estoqueDisponivel,
                            1
                        )
                    );
                }
            }
        }

    } catch (Exception e) {

        JOptionPane.showMessageDialog(
            this,
            "Erro ao buscar produto: " + e.getMessage()
        );
    }
}

